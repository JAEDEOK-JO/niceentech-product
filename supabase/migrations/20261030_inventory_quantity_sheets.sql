CREATE TABLE IF NOT EXISTS public.inventory_quantity_sheets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id bigint NOT NULL REFERENCES public.company_list(id) ON DELETE RESTRICT,
  material_type text NOT NULL CHECK (material_type IN ('raw', 'subsidiary')),
  site_name text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.inventory_quantity_sheet_columns (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sheet_id bigint NOT NULL REFERENCES public.inventory_quantity_sheets(id) ON DELETE CASCADE,
  sort_order integer NOT NULL,
  column_date text NOT NULL DEFAULT '',
  memo text NOT NULL DEFAULT '',
  CONSTRAINT inventory_quantity_sheet_columns_order_unique UNIQUE (sheet_id, sort_order)
);

CREATE TABLE IF NOT EXISTS public.inventory_quantity_sheet_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  column_id bigint NOT NULL REFERENCES public.inventory_quantity_sheet_columns(id) ON DELETE CASCADE,
  material_group text NOT NULL DEFAULT '',
  spec text NOT NULL DEFAULT '',
  quantity numeric(12, 3) NOT NULL CHECK (quantity <> 0)
);

CREATE INDEX IF NOT EXISTS inventory_quantity_sheets_company_idx
  ON public.inventory_quantity_sheets (company_id, material_type, created_at DESC);

CREATE INDEX IF NOT EXISTS inventory_quantity_sheet_columns_sheet_idx
  ON public.inventory_quantity_sheet_columns (sheet_id, sort_order);

CREATE INDEX IF NOT EXISTS inventory_quantity_sheet_items_column_idx
  ON public.inventory_quantity_sheet_items (column_id);

ALTER TABLE public.inventory_quantity_sheets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inventory_quantity_sheet_columns ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inventory_quantity_sheet_items ENABLE ROW LEVEL SECURITY;

