export const RECORD_RULES = `[기록 작성]
판정한 모든 파이프를 records에 한 건씩 기록한다. 포함, 제외, 불확실 모두 기록한다. 25 관경 분기만 있는 짧은 관처럼 판정 대상이 아닌 부속은 기록하지 않아도 된다.
- scope: 도번, 층·세대·구역 등 이 파이프가 속한 적용 범위
- pipe_no: 도면에 적힌 파이프 번호. 없으면 빈 문자열
- pipe_part: 같은 번호 안에서 이 파이프를 구분하는 값. 예: "왼쪽 첫 번째 50관", "관경 변경 뒤 40관". 번호 안에 파이프가 하나면 "단일"
- location: 페이지 안 위치 설명
- region: 페이지 이미지 기준 이 파이프와 치수를 감싸는 영역. 왼쪽 위가 0,0이고 오른쪽 아래가 1,1인 비율 좌표
- body_diameter: 본체 관경. 읽을 수 없으면 unknown, 대상 외 관경이면 other
- has_hole: 구멍 가공 위치가 확인되면 yes, 없으면 no, 판단할 수 없으면 unknown
- total_length: 전체 길이 치수 원문
- hole_dimension: 구멍·분기 위치를 나타내는 중간 치수 원문 하나 이상
- ea_text, set_text: 이 파이프에 적용되는 EA, SET 표기 원문. 없으면 빈 문자열
- multiplier: 이 파이프 1개에 적용되는 최종 배수. 반복 표기가 없으면 1
- multiplier_basis: 배수를 그렇게 정한 근거. 예: "4EA", "20F 1SET + 16F 1SET = 2SET"
- status: 구멍 있는 대상 관경 파이프로 확정되면 included, 구멍이 없거나 대상 관경이 아니면 excluded, 관경·구멍 위치·배수 중 하나라도 확정할 수 없으면 uncertain
- reason: 판정 이유를 짧게

수량 합계나 관경별 총수량은 출력하지 않는다. 합산은 별도로 한다.`
