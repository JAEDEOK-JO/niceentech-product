const shiftMonth = (transaction, offset, suffix) => {
  const month = transaction.month + offset
  return {
    ...transaction,
    id: `${transaction.id}-${suffix}`,
    year: month > 12 ? transaction.year + 1 : transaction.year,
    month: month > 12 ? month - 12 : month,
  }
}

export const buildTransactions = (outbound, inbound) => {
  const base = [
    ...outbound.map((column) => ({ ...column, type: 'out' })),
    ...inbound.map((column) => ({ ...column, type: 'in' })),
  ]
  return [...base, ...base.map((t) => shiftMonth(t, 2, 'a')), ...base.map((t) => shiftMonth(t, 4, 'b'))].sort(
    (a, b) => a.year - b.year || a.month - b.month || a.day - b.day,
  )
}

